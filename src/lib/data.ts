let cachedLeadData: Lead[] | null = null;
let todayLeads: number | null = null;

const imageBasedPattern = [
  25, 10, 20, 35, 58, 40, 80, 35, 10, 20, 38, 45, 42, 50, 20, 5, 110, 5, 2, 2, 3, 1, 2, 5, 4, 3, 2, 1, 2, 3, 4
];


function generateLeadData(): Lead[] {
  if (cachedLeadData) {
    return cachedLeadData;
  }
  
  const data: Lead[] = [];
  const year = 2025; // Fixed year for consistency

  for (let month = 0; month < 12; month++) {
    const daysInMonth = new Date(year, month + 1, 0).getDate();
    for (let day = 1; day <= daysInMonth; day++) {
        const date = new Date(year, month, day);
        const dateString = date.toISOString().split('T')[0];

        // Generate data for all districts in Karnataka
        const karnatakaDistricts = indianStatesAndDistricts['Karnataka'];
        karnatakaDistricts.forEach(district => {
            // Use the pattern for November, otherwise use random data
            let leads = 0;
            if (month === 10) { // November
              leads = imageBasedPattern[day - 1] !== undefined ? imageBasedPattern[day - 1] + Math.floor(Math.random() * 10 - 5) : 2;
              leads = Math.max(0, leads); // ensure leads are not negative
            } else {
              const isWeekend = date.getDay() === 0 || date.getDay() === 6;
              if (Math.random() > 0.3) { 
                const baseLeads = isWeekend ? 15 : 5;
                const randomFactor = Math.random() * (50 + Math.sin(day * Math.PI / 15) * 45);
                leads = Math.floor(baseLeads + randomFactor);
              }
            }
            
            data.push({
              date: dateString,
              state: 'Karnataka',
              city: district,
              leads: leads,
            });
        });

        // Add some random data for other states too
        for (let j = 0; j < 5; j++) { // Increased loop to generate more data
            const randomStateName = Object.keys(indianStatesAndDistricts)[Math.floor(Math.random() * Object.keys(indianStatesAndDistricts).length)];
            if(randomStateName !== 'Karnataka') {
                const cities = indianStatesAndDistricts[randomStateName];
                const randomCityName = cities[Math.floor(Math.random() * cities.length)];
                
                const isWeekend = date.getDay() === 0 || date.getDay() === 6;
                const baseLeads = isWeekend ? 20 : 10; // Increased base leads
                const leads = Math.floor(baseLeads + Math.random() * 40 + (day/2)); // Increased random factor
                
                data.push({
                  date: dateString,
                  state: randomStateName,
                  city: randomCityName,
                  leads: leads,
                });
            }
        }
    }
  }

  cachedLeadData = data;
  return data;
}

export function getLeadData(): Lead[] {
  return generateLeadData();
}

export function getLeadsForToday(): number {
  if (todayLeads !== null) {
      return todayLeads;
  }

  const allLeads = getLeadData();
  const today = new Date('2025-11-15T12:00:00Z');
  const todayString = today.toISOString().split('T')[0];

  const total = allLeads
    .filter((lead) => lead.date === todayString)
    .reduce((sum, lead) => sum + lead.leads, 0);

  todayLeads = total;
  return total;
}
